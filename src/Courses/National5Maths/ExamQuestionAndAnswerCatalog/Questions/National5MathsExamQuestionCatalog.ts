export function getN5MathsExamQuestionsByFamilyId(
  familyId: string
) {
  return (
    N5_MATHS_EXAM_QUESTION_CATALOG
      .filter(
        (
          question:
            ExamQuestionCatalogEntry
        ) =>
          question.familyId ===
          familyId
      )
  );
}



export function getN5MathsExamQuestionsBySkillId(
  skillId: string
) {
  return (
    N5_MATHS_EXAM_QUESTION_CATALOG
      .filter(
        (
          question:
            ExamQuestionCatalogEntry
        ) =>
          question.skillIds.includes(
            skillId
          )
      )
  );
}



export function getN5MathsExamQuestionsByConceptId(
  conceptId: string
) {
  return (
    N5_MATHS_EXAM_QUESTION_CATALOG
      .filter(
        (
          question:
            ExamQuestionCatalogEntry
        ) =>
          question.conceptIds.includes(
            conceptId
          )
      )
  );
}