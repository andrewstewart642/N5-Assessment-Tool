export const WHITE_ACCENT_OPTION: AccentOption = "word-neutral-white";
export const BLACK_ACCENT_OPTION: AccentOption = "word-neutral-black";

export function getAccentLabel(id: AccentOption): string {
  if (id === WHITE_ACCENT_OPTION) return "White";
  if (id === BLACK_ACCENT_OPTION) return "Black";
  if (id.startsWith("word-neutral")) return "Grey";
  if (id.startsWith("word-r")) return "Word colour";

  return id;
}